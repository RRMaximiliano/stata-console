const ABBREVIATIONS: Record<string, string> = {
    gen: 'generate', reg: 'regress', su: 'summarize', tab: 'tabulate',
    des: 'describe', di: 'display', cor: 'correlate', br: 'browse',
    bys: 'bysort', qui: 'quietly', cap: 'capture', noi: 'noisily',
    loc: 'local', glo: 'global', pr: 'program', u: 'use', sa: 'save',
};

export const COMMAND_ALIASES = Object.entries(ABBREVIATIONS).map(([label, command]) => ({
    label, command, detail: COMMANDS.find(item => item.label === command)!.detail,
}));

export function resolveCommand(word: string): StataCommand | undefined {
    const direct = COMMANDS.find(command => command.label === word);
    if (direct) { return direct; }
    const canonical = Object.entries(ABBREVIATIONS).find(([minimum, full]) => word.length >= minimum.length && full.startsWith(word) && word.startsWith(minimum))?.[1];
    return COMMANDS.find(command => command.label === canonical);
}
